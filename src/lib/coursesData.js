export function getCourseBySlug(slug) {
  return COURSES.find((c) => c.slug === slug);
}

export function getRelatedCourses(slug, count = 3) {
  const index = COURSES.findIndex((c) => c.slug === slug);
  if (index === -1) return COURSES.slice(0, count);
  const related = [];
  for (let i = 1; related.length < count && i <= COURSES.length; i += 1) {
    const course = COURSES[(index + i) % COURSES.length];
    if (course.slug !== slug) related.push(course);
  }
  return related;
}
